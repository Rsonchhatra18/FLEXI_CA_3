"""Study Pack automation – a deterministic multi-step workflow (like an n8n flow).

  trigger (CLI / UI button / new file in inbox/)
     → load document from ChromaDB
     → summary (MAIN model)
     → 5 key terms with definitions
     → 5 MCQs with answers
     → save outputs/<doc>_study_pack.md
     → log the run to outputs/runs.jsonl

Usage:
  python -m automation.study_pack --doc rag_techniques.md
  python -m automation.study_pack --inbox
"""
import argparse
import json
import shutil
import sys
import time
from datetime import datetime
from pathlib import Path

from agent.llm import get_llm
from kb import store

ROOT = Path(__file__).resolve().parent.parent
OUTPUTS = ROOT / "outputs"
INBOX = ROOT / "inbox"
RUNS_LOG = OUTPUTS / "runs.jsonl"
MAX_CHARS = 6000

STEPS = ["load_document", "summarise", "key_terms", "mcqs", "save_markdown"]


def _ask(prompt: str) -> str:
    return get_llm("main", temperature=0.2).invoke(prompt).content.strip()


def _log_run(doc: str, status: str, seconds: float, output: str) -> None:
    OUTPUTS.mkdir(exist_ok=True)
    record = {"timestamp": datetime.now().isoformat(timespec="seconds"), "doc": doc,
              "status": status, "seconds": round(seconds, 1), "output": output}
    with RUNS_LOG.open("a", encoding="utf-8") as f:
        f.write(json.dumps(record) + "\n")


def run_study_pack(doc_name: str, on_step=None) -> dict:
    """Run the full workflow for one document. on_step(step_name, status) is called after each step."""
    notify = on_step or (lambda step, status: None)
    start = time.time()
    try:
        # Step 1 – load
        text = store.get_document_text(doc_name, max_chars=MAX_CHARS)
        if not text:
            raise ValueError(f"'{doc_name}' is not in the knowledge base")
        notify("load_document", f"loaded {len(text)} characters")

        # Step 2 – summary
        summary = _ask("Summarise the following study material for a university student in "
                       "5–7 concise bullet points. Use markdown bullets only.\n\n" + text)
        notify("summarise", "summary written")

        # Step 3 – key terms
        terms = _ask("From the study material below, pick exactly 5 key terms. Format each as a markdown "
                     "bullet: **Term** – one-sentence definition. Output only the 5 bullets.\n\n" + text)
        notify("key_terms", "5 key terms extracted")

        # Step 4 – MCQs
        mcqs = _ask("Write exactly 5 multiple-choice questions that test understanding of the material "
                    "below. Use this markdown format for each:\n"
                    "**Q1. question?**\n- A) ...\n- B) ...\n- C) ...\n- D) ...\n\n*Answer: B – short reason*\n\n"
                    "Output only the questions.\n\n" + text)
        notify("mcqs", "5 MCQs generated")

        # Step 5 – save
        OUTPUTS.mkdir(exist_ok=True)
        out_path = OUTPUTS / f"{Path(doc_name).stem}_study_pack.md"
        stamp = datetime.now().strftime("%Y-%m-%d %H:%M")
        markdown = (f"# 📘 Study Pack – {doc_name}\n\n_Generated by StudyPilot on {stamp}_\n\n"
                    f"## 📝 Summary\n\n{summary}\n\n## 🔑 Key Terms\n\n{terms}\n\n"
                    f"## ❓ Practice MCQs\n\n{mcqs}\n")
        out_path.write_text(markdown, encoding="utf-8")
        seconds = time.time() - start
        notify("save_markdown", f"saved outputs/{out_path.name}")

        _log_run(doc_name, "success", seconds, f"outputs/{out_path.name}")
        return {"status": "success", "doc": doc_name, "path": str(out_path),
                "markdown": markdown, "seconds": round(seconds, 1)}
    except Exception as e:
        seconds = time.time() - start
        _log_run(doc_name, f"failed: {type(e).__name__}", seconds, "")
        notify("error", str(e)[:200])
        return {"status": "failed", "doc": doc_name, "error": str(e), "seconds": round(seconds, 1)}


def process_inbox(on_step=None) -> list[dict]:
    """Trigger: ingest every new file in inbox/ and build a study pack for it.

    Processed files are moved to inbox/processed/ so they don't trigger again.
    """
    INBOX.mkdir(exist_ok=True)
    done_dir = INBOX / "processed"
    results = []
    for path in sorted(p for p in INBOX.iterdir() if p.is_file() and p.suffix.lower() in store.SUPPORTED):
        ingest = store.ingest_file(path)
        if on_step:
            on_step(f"ingest {path.name}", ingest["status"])
        pack = run_study_pack(path.name, on_step=on_step)
        pack["ingest"] = ingest["status"]
        results.append(pack)
        done_dir.mkdir(exist_ok=True)
        shutil.move(str(path), done_dir / path.name)
    return results


def read_runs() -> list[dict]:
    if not RUNS_LOG.exists():
        return []
    return [json.loads(line) for line in RUNS_LOG.read_text(encoding="utf-8").splitlines() if line.strip()]


def main():
    sys.stdout.reconfigure(encoding="utf-8")
    parser = argparse.ArgumentParser(description="StudyPilot study-pack automation")
    group = parser.add_mutually_exclusive_group(required=True)
    group.add_argument("--doc", help="document name in the knowledge base, e.g. rag_techniques.md")
    group.add_argument("--inbox", action="store_true", help="process every new file in inbox/")
    args = parser.parse_args()

    log = lambda step, status: print(f"  ✔ {step:<16} {status}")
    if args.doc:
        print(f"Running study pack for {args.doc}")
        r = run_study_pack(args.doc, on_step=log)
        print(f"→ {r['status']} in {r['seconds']}s", r.get("path") or r.get("error"))
    else:
        print("Processing inbox/ ...")
        results = process_inbox(on_step=log)
        if not results:
            print("  inbox is empty – drop a PDF/TXT/MD file into inbox/ and run again")
        for r in results:
            print(f"→ {r['doc']}: {r['status']}", r.get("path") or r.get("error"))


if __name__ == "__main__":
    main()
